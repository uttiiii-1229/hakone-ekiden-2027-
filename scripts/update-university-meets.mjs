import fs from 'node:fs/promises';
import path from 'node:path';
import * as cheerio from 'cheerio';

const ROOT=process.cwd();
const manifestPath=path.join(ROOT,'data','university-meet-sources.json');
const outputPath=path.join(ROOT,'hakone2027-site 3','university-meet-results-auto.js');
const sources=JSON.parse(await fs.readFile(manifestPath,'utf8'));

const fw=s=>String(s||'').normalize('NFKC').replace(/\s+/g,' ').trim();
function eligibleEvent(text){
  const t=fw(text).toLowerCase();
  if(/競歩|walking|walk|3000msc|3000msc|3000m障害|3000ｍsc|3000ｍｓｃ/.test(t)) return false;
  if(/5000m|5000ｍ|10000m|10000ｍ|ハーフ|half marathon|20km|20ｋｍ|30km|30ｋｍ|15km|15ｋｍ|10km|10ｋｍ|5km|5ｋｍ/.test(t)) return true;
  return false;
}
function absolutize(base,href){try{return new URL(href,base).href}catch{return null}}
function gradeFromName(name){
  const m=String(name||'').match(/\((M\d|D\d|\d)\)/i);
  return m?m[1]:'';
}
function cleanName(name){return fw(name).replace(/\((?:M\d|D\d|\d)\)$/i,'').trim()}
function normalizeTeam(team){return fw(team).replace(/大$/,'大学').replace('國學院大学','國學院大學')}
async function fetchText(url){
  const res=await fetch(url,{headers:{'user-agent':'UniversityEkidenDatabase/1.0 (+github-actions)'}});
  if(!res.ok) throw new Error(`${res.status} ${url}`);
  return await res.text();
}
async function parseIuau(source){
  const indexHtml=await fetchText(source.indexUrl);
  const $=cheerio.load(indexHtml);
  const links=new Map();
  $('a[href]').each((_,a)=>{
    const href=$(a).attr('href');
    if(!href||!/(?:rel|REL)\d+\.html?/i.test(href)) return;
    const tr=$(a).closest('tr');
    const text=fw(tr.text());
    if(!eligibleEvent(text)) return;
    if(source.includeGenders?.length && !source.includeGenders.some(g=>text.includes(g))) return;
    const url=absolutize(source.indexUrl,href);
    if(url) links.set(url,text);
  });
  const events={};
  for(const [url,indexText] of links){
    try{
      const html=await fetchText(url);
      const $$=cheerio.load(html);
      const title=fw($$('h1').first().text()||$$('title').text()||indexText);
      if(!eligibleEvent(title)) continue;
      const eventName=title.replace(/\s+/g,' ');
      const rows=[];
      $$('table').first().find('tr').slice(1).each((_,tr)=>{
        const cells=$$(tr).find('th,td').map((_,td)=>fw($$(td).text())).get();
        if(cells.length<5) return;
        let rank=cells[0]||'—';
        let name='',team='',record='',comment='';
        // IUAU standard: rank, ORD, bib, name, team, record, comment
        if(cells.length>=7){name=cells[3];team=cells[4];record=cells[5];comment=cells[6]||'';}
        else if(cells.length>=6){name=cells[2];team=cells[3];record=cells[4];comment=cells[5]||'';}
        else return;
        const grade=gradeFromName(name);
        name=cleanName(name);
        team=normalizeTeam(team);
        if(!name||!team) return;
        if(!record && !/DNS|DNF|DQ|NM/i.test(comment)) return;
        rows.push([rank||'—',name,team,grade,record||'—',comment]);
      });
      if(rows.length) events[eventName]={url,rows};
    }catch(err){console.warn('skip result',url,err.message)}
  }
  return {id:source.id,year:source.year,name:source.name,events};
}

const db={generatedAt:new Date().toISOString(),rule:'distance > 3000m; running events only; race walking and 3000mSC excluded',meets:{}};
for(const source of sources){
  try{
    if(source.adapter==='iuau-web-results'){
      const meet=await parseIuau(source);
      db.meets[source.id]=meet;
    }
  }catch(err){console.error('source failed',source.id,err.message)}
}
const js='// Auto-generated by scripts/update-university-meets.mjs\nwindow.universityMeetResultsAutoDB = '+JSON.stringify(db,null,2)+';\n';
await fs.writeFile(outputPath,js,'utf8');
console.log('wrote',outputPath,Object.keys(db.meets).length,'meets');
